def find_script(name: str) -> Optional[Path]:
    for rel in SCRIPT_CANDIDATES[name]:
        path = REPO_ROOT / rel
        if path.is_file():
            return path
    return None


def run_script(path: Path, op: str, payload: Dict[str, Any]) -> Dict[str, Any]:
    proc = subprocess.run([sys.executable, str(path), op], input=json.dumps(payload), capture_output=True,
                          text=True, timeout=120, cwd=str(REPO_ROOT))
    try:
        out = json.loads(proc.stdout)
    except ValueError:
        raise GenError("%s %s printed no JSON (exit %d): %s" % (path.name, op, proc.returncode,
                                                                 (proc.stderr or proc.stdout)[-600:]))
    if not isinstance(out, dict):
        raise GenError("%s %s printed %s, not a JSON object" % (path.name, op, type(out).__name__))
    return out


def _find(obj: Any, key: str) -> List[Any]:
    """Every value stored under `key` anywhere in obj (depth-first)."""
    hits = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k == key:
                hits.append(v)
            hits.extend(_find(v, key))
    elif isinstance(obj, list):
        for v in obj:
            hits.extend(_find(v, key))
    return hits


def _first(obj: Any, *keys: str) -> Any:
    for key in keys:
        hits = _find(obj, key)
        if hits:
            return hits[0]
    return None


def _same(expected: Any, got: Any) -> bool:
    if got is None:
        return False
    if isinstance(expected, bool) or isinstance(got, bool):
        return expected == got
    try:
        return dec(expected) == dec(got)
    except FixtureError:
        return str(expected) == str(got)


