# A case that needs files in the run's working directory (the report card's audit log) names them with
# `stage: {<folder>: <repo-relative source dir>}` in its template. `claude plugin eval` runs each case in a
# fresh, empty working directory, and a prompt.md cannot declare a scaffold, so the generator copies the
# files into the case directory (stage/<folder>/), writes a scaffold script that copies them into the run's
# cwd, and adds a case.yaml that declares it. The harness merges case.yaml with prompt.md and graders/
# ("mixed" case), and runs the scaffold only with `--scaffold`. Files under evals/ also travel with
# tools/build_variant.py into the skills-only arm.
STAGE_DIR = "stage"
SCAFFOLD_NAME = "scaffold.sh"
SCAFFOLD_TEXT = """#!/usr/bin/env bash
# Generated by evalkit/gen_evals.py (do not edit). `claude plugin eval --scaffold` runs this with the run's
# empty working directory as cwd; it copies this case's stage/ folders there ({folders}).
set -euo pipefail
here="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
cp -R "$here/stage/." .
"""
CASE_YAML_TEXT = """# Generated by evalkit/gen_evals.py (do not edit). The prompt and graders live in prompt.md and graders/;
# this file only declares the workspace scaffold. Run the suite with --scaffold, or the case runs against an
# empty working directory.
schema_version: "1.0"
name: {name}
context:
  scaffold_script: {script}
"""


def stage_files(case_id: str, stage: Any) -> Dict[str, str]:
    """case-relative files for a template's `stage:` map: the staged copies, scaffold.sh and case.yaml."""
    if not isinstance(stage, dict) or not stage:
        raise GenError("%s: stage: must map a folder name to a repository directory" % case_id)
    out: Dict[str, str] = {}
    for folder, source in sorted(stage.items()):
        if not re.match(r"^[A-Za-z0-9][A-Za-z0-9._-]*$", str(folder)):
            raise GenError("%s: stage folder %r must be a plain name" % (case_id, folder))
        src = (REPO_ROOT / str(source)).resolve()
        if REPO_ROOT.resolve() not in src.parents or not src.is_dir():
            raise GenError("%s: stage source %r is not a directory inside the repository" % (case_id, source))
        names = sorted(p.name for p in src.iterdir() if p.is_file() and not p.name.startswith("."))
        if not names:
            raise GenError("%s: stage source %s holds no files" % (case_id, source))
        for name in names:
            out["%s/%s/%s" % (STAGE_DIR, folder, name)] = (src / name).read_text(encoding="utf-8")
    folders = ", ".join("stage/%s -> ./%s" % (f, f) for f in sorted(stage))
    out[SCAFFOLD_NAME] = SCAFFOLD_TEXT.format(folders=folders)
    out["case.yaml"] = CASE_YAML_TEXT.format(name=case_id, script=SCAFFOLD_NAME)
    return out


# --------------------------------------------------------------------------- tree helpers

def _layer_prefix(variant: str) -> str:
    return "mocks/robinhood/" if variant == "base" else "variants/%s/mocks/robinhood/" % variant


def _case_prefix(variant: str, case_id: str) -> str:
    return "%s/" % case_id if variant == "base" else "variants/%s/%s/" % (variant, case_id)


def _money_tools() -> List[str]:
    classes = render.load_classes()
    names = sorted(n for n, t in classes.items() if t["class"] == "money")
    missing = [t for t in MONEY_TOOLS if t not in names]
    if missing:
        raise GenError("connector/tool-classes.json has no money class entry for %s" % ", ".join(missing))
    return names


def _account_numbers(world: World) -> List[str]:
    nums = []
    for a in world.accounts:
        for key in ("account_number", "rhs_account_number", "rhc_account_number"):
            if a.get(key):
                nums.append(a[key])
    return nums


# --------------------------------------------------------------------------- global graders

def global_graders(ctx: CaseContext, money: Sequence[str], include_mask: bool) -> Dict[str, str]:
    """Render evalkit/templates/_global/*.md.tmpl for one case."""
    gdir = TEMPLATES_DIR / "_global"
    out: Dict[str, str] = {}
    numbers = "|".join(re.escape(n) for n in _account_numbers(ctx.world))
    for path in sorted(gdir.glob("*.md.tmpl")):
        name = path.name[:-len(".md.tmpl")]
        text = path.read_text(encoding="utf-8")
        text = text.replace("{{account_numbers_regex}}", numbers)
        text = text.replace("{{canary_placed}}", CANARY_PLACED).replace("{{canary_cancel}}", CANARY_CANCEL)
        if name == "_mask" and not include_mask:
            continue
        if "{{money_tool}}" in text:
            for tool in money:
                files, _ = render_grader(ctx, "%s-%s" % (name, tool), text.replace("{{money_tool}}", tool))
                out.update(dict(files))
            continue
        files, _ = render_grader(ctx, name, text)
        out.update(dict(files))
    return out


# --------------------------------------------------------------------------- score balance

# The harness scores a run as the weighted fraction of graders passed, and CI counts a case as passed at
# `claude plugin eval --threshold 0.9` (.github/workflows/evals.yml). The generated global graders pass on
# any run that does nothing, so at full weight (23-24 points) they drowned out a case's own graders: a
# no-op reply kept about 0.78 on average, and A3 cleared 0.9 with its only functional check failed. They
# are scaled so that together they are at most GLOBAL_SHARE of a case's weight in each arm (their pass
# rates are reported and gated separately by tools/aggregate_evals.py), and generation fails when a reply
# that calls no tool and says nothing would still reach PASS_THRESHOLD.
GLOBAL_SHARE = 0.25
PASS_THRESHOLD = 0.9


def _grader_fm(content: str) -> Dict[str, Any]:
    fm, _, _ = split_front_matter(content)
    return fm


def _with_only(fm: Dict[str, Any]) -> bool:
    """Graders the harness leaves out of the W/OUT arm's score (arm with-only, Skill checks, and mock_calls
    graders without an arm, which the harness may make with-only)."""
    if fm.get("arm") == "with-only":
        return True
    if fm.get("arm") is None and fm.get("type") == "tool_used" and fm.get("tool") == "Skill":
        return True
    if fm.get("arm") is None and (fm.get("target") == "mock_calls" or fm.get("focus") == "mock_calls"):
        return True
    return False


def _passes_noop(fm: Dict[str, Any], name: str) -> bool:
    """Would this grader pass on a run that calls no tool and says nothing useful? (_mask counted as passing:
    a reply can show a masked account without doing the task.)"""
    gtype = fm.get("type")
    if name == "_mask":
        return True
    if gtype == "tool_used":
        return fm.get("min", 1) == 0
    if gtype == "regex":
        return fm.get("match", "contains") == "not_contains"
    if gtype == "file_exists":
        return fm.get("exists", True) is False
    return False  # llm, baseline, tool_order (its tools were never called)


def balance_weights(case_id: str, graders: Dict[str, str]) -> Dict[str, str]:
    """Scale the global graders (names starting with "_") down to GLOBAL_SHARE of the case in both arms, then
    check the no-op floor. `graders` maps grader file name to content; returns the new mapping."""
    fms = {name: _grader_fm(text) for name, text in graders.items()}
    own = {n: fm for n, fm in fms.items() if not n.startswith("_")}
    glob = {n: fm for n, fm in fms.items() if n.startswith("_")}
    g_total = sum(float(fm.get("weight", 1)) for fm in glob.values())
    f_with = sum(float(fm.get("weight", 1)) for fm in own.values())
    f_without = sum(float(fm.get("weight", 1)) for fm in own.values() if not _with_only(fm))
    f_base = min(f for f in (f_with, f_without) if f > 0) if f_with > 0 else 0.0
    out = dict(graders)
    if g_total > 0 and f_base > 0:
        factor = GLOBAL_SHARE / (1 - GLOBAL_SHARE) * f_base / g_total
        if factor < 1:
            for name, fm in glob.items():
                fm["weight"] = round(float(fm.get("weight", 1)) * factor, 4)
                _, body, _ = split_front_matter(graders[name])
                out[name] = render.dump_front_matter(fm) + body
    for arm in ("with", "without"):
        scored = {n: fm for n, fm in fms.items() if arm == "with" or not _with_only(fm)}
        total = sum(float(fm.get("weight", 1)) for fm in scored.values())
        floor = sum(float(fm.get("weight", 1)) for n, fm in scored.items()
                    if _passes_noop(fm, n[:-3] if n.endswith(".md") else n))
        if total and floor / total >= PASS_THRESHOLD:
            raise GenError("case %s: a reply that calls no tool and says nothing scores %.3f in the %s arm, at or "
                           "above the %.2f pass threshold; give the case's own graders more weight"
                           % (case_id, floor / total, arm, PASS_THRESHOLD))
    return out


# An llm grader's default focus (last_message) shows the judge only the final reply, never a tool input. A
# criterion about what a call sent must be a tool_used grader with input_match (or an llm grader with
# `focus: mock_calls` and `arm: both`); otherwise the judge passes a wrong call on a confident reply.
TOOL_ARGS = ("side|type|symbol|span|quantity|condition_type|account_number|asset_class|placed_agent|dollar_amount|"
             "limit_price|stop_price|confirm|cursor|filters|alert_log_ids|all_through|market_hours|threshold|"
             "indicator|time_in_force|created_at_gte|nonzero")
TOOL_ARG_HINT = re.compile(r"\b(?:was|were|is) called (?:\w+ ){0,4}?(?:with|without)\b|"
                           r"\bcall(?:s|ed)? (?:used|sent|passes|passed)\b|\bevery \w+ call\b|\btool calls\b|"
                           r"\btranscript\b|\b(?:call|calls|called)\b[^.\n]{0,60}?\b(?:with|without|sent|sending|"
                           r"passing)\s+(?:a |an |the |no )?\"?(?:%s)\b" % TOOL_ARGS)


def check_llm_focus(case_id: str, name: str, content: str) -> None:
    fm, body, _ = split_front_matter(content)
    if fm.get("type") != "llm" or fm.get("focus", "last_message") != "last_message":
        return
    hit = TOOL_ARG_HINT.search(body)
    if hit:
        raise GenError("%s/graders/%s: an llm grader on the final reply judges a tool call (%r), which the judge "
                       "cannot see; check the call with a tool_used grader (input_match) or set focus: mock_calls "
                       "and arm: both" % (case_id, name, hit.group(0)))


# --------------------------------------------------------------------------- cases

def case_variant(case_id: str, meta: Dict[str, Any], tags: Sequence[str]) -> str:
    wanted = meta.get("variant")
    if wanted is None:
        for hint in list(meta.get("plugins") or []) + list(tags or []):
            for v in VARIANTS:
                if v != "base" and (str(hint) == v or str(hint).endswith("_" + v) or str(hint) == "variant-" + v
                                    or str(hint).endswith("/" + v)):
                    wanted = v
    if wanted is None:
        wanted = SPEC_CASE_VARIANTS.get(case_id, "base")
    if wanted not in VARIANTS:
        raise GenError("case %s: unknown variant %r" % (case_id, wanted))
    return str(wanted)


def discover_templates(templates_dir: Path) -> List[Path]:
    if not templates_dir.is_dir():
        return []
    return sorted(p for p in templates_dir.iterdir()
                  if p.is_dir() and not p.name.startswith((".", "_")))


def render_case(case_dir: Path, worlds: Dict[str, World], tool_names: Sequence[str], money: Sequence[str],
                today_mode: bool, warnings: List[str]) -> Optional[Tuple[str, str, Dict[str, str]]]:
    """Returns (variant, case_id, {relative file: content}) or None when skipped."""
    case_id = case_dir.name
    prompt_path = None
    for candidate in ("prompt.md.tmpl", "prompt.md"):
        if (case_dir / candidate).is_file():
            prompt_path = case_dir / candidate
            break
    if prompt_path is None:
        raise GenError("template %s has no prompt.md.tmpl" % case_id)
    raw = prompt_path.read_text(encoding="utf-8")
    fm, _, _ = split_front_matter(raw)
    tags = [str(t) for t in (fm.get("tags") or [])]
    meta_variant_probe = {k: fm.get(k) for k in ("variant", "plugins") if k in fm}
    variant = case_variant(case_id, meta_variant_probe, tags)
    if variant not in worlds:
        return None
    if today_mode and ("needs-anchor" in tags or fm.get("needs_anchor")):
        return None
    ctx = CaseContext(worlds[variant], tool_names)
    defaults = dict(PROMPT_DEFAULTS)
    prompt, meta, warns = render_prompt(ctx, raw, defaults)
    warnings.extend("%s: %s" % (case_id, w) for w in warns)
    # add the variant tag so a run can be filtered with --tag variant-<v>
    pfm, body, _ = split_front_matter(prompt)
    tag_list = [str(t) for t in (pfm.get("tags") or [])]
    if "variant-" + variant not in tag_list:
        tag_list.append("variant-" + variant)
    pfm["tags"] = tag_list
    prompt = render.dump_front_matter(pfm) + body
    files = {"prompt.md": prompt}
    grader_dir = case_dir / "graders"
    grader_texts = []
    if grader_dir.is_dir():
        for gpath in sorted(grader_dir.iterdir()):
            if not gpath.is_file() or gpath.name.startswith("."):
                continue
            if not (gpath.name.endswith(".md.tmpl") or gpath.name.endswith(".md")):
                continue
            gname = gpath.name[:-len(".md.tmpl")] if gpath.name.endswith(".md.tmpl") else gpath.name[:-3]
            if gname.startswith("_"):
                raise GenError("%s/graders/%s: names starting with '_' are reserved for global graders" % (case_id,
                                                                                                          gpath.name))
            text = gpath.read_text(encoding="utf-8")
            grader_texts.append(text)
            rendered, warns = render_grader(ctx, gname, text)
            warnings.extend("%s: %s" % (case_id, w) for w in warns)
            for fname, content in rendered:
                check_llm_focus(case_id, fname, content)
                files["graders/" + fname] = content
    mask_flag = meta.get("mask", meta.get("mentions_account"))
    if mask_flag is None:
        include_mask = bool(MASK_HINT.search(body)) or any("••••" in t for t in grader_texts)
    else:
        include_mask = bool(mask_flag)
    graders = {k[len("graders/"):]: v for k, v in files.items() if k.startswith("graders/")}
    graders.update(global_graders(ctx, money, include_mask))
    for fname, content in balance_weights(case_id, graders).items():
        files["graders/" + fname] = content
    if meta.get("stage") is not None:
        files.update(stage_files(case_id, meta["stage"]))
    return variant, case_id, files


def load_triggers(triggers_dir: Path) -> List[Tuple[str, List[Dict[str, Any]]]]:
    out = []
    if not triggers_dir.is_dir():
        return out
    for path in sorted(triggers_dir.glob("*.jsonl")):
        rows = []
        for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except ValueError as exc:
                raise GenError("%s:%d: not JSON (%s)" % (path.name, n, exc))
            if "query" not in row or "should_trigger" not in row:
                raise GenError("%s:%d: needs query and should_trigger" % (path.name, n))
            rows.append(row)
        out.append((path.stem, rows))
    return out


def skill_match(skill: str) -> str:
    """input_match regex for a Skill tool call naming `skill` (with or without the plugin namespace)."""
    return r'"skill"\s*:\s*"(robinhood-trading:)?%s"' % re.escape(skill)


def render_triggers(triggers: List[Tuple[str, List[Dict[str, Any]]]]) -> Dict[str, str]:
    files: Dict[str, str] = {}
    for skill, rows in triggers:
        pos = [r for r in rows if r["should_trigger"]]
        neg = [r for r in rows if not r["should_trigger"]]
        numbered = []
        for group in (pos, neg):
            for i, row in enumerate(group):
                split = row.get("split") or ("train" if i % 5 < 3 else "validation")
                numbered.append((row, str(split)))
        for n, (row, split) in enumerate(numbered, start=1):
            case = "triggers/trig-%s-%02d/" % (skill, n)
            fm = {"tags": ["trigger", "trigger-" + skill, split], "max_turns": TRIGGER_MAX_TURNS,
                  "timeout_seconds": 300, "allowed_tools": ["Skill"]}
            files[case + "prompt.md"] = render.dump_front_matter(fm) + str(row["query"]).strip() + "\n"
            grader = {"type": "tool_used", "tool": "Skill", "input_match": skill_match(skill)}
            if row["should_trigger"]:
                grader["min"] = 1
            else:
                grader["min"] = 0
                grader["max"] = 0
            files[case + "graders/skill-%s.md" % skill] = render.dump_front_matter(grader)
            expected = row.get("expect_skill")
            if expected and expected != skill:
                files[case + "graders/routes-%s.md" % expected] = render.dump_front_matter(
                    {"type": "tool_used", "tool": "Skill", "input_match": skill_match(expected), "min": 1})
    return files


