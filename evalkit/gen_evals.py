#!/usr/bin/env python3
"""Generate the `claude plugin eval` suite for Preflight (unofficial) from the fixture household.

    python3 evalkit/gen_evals.py [--anchor 2026-11-16T20:05:00-05:00 | today] [--variant all|base,regular,...]
                                 [--check] [--out DIR]
    python3 evalkit/gen_evals.py --golden [--check] [--allow-partial]

What it writes (everything under evals/ except results/ and .replay/ directories is generated; never
hand-edit it, edit evalkit/ and re-run):

  evals/mocks/robinhood/                 base mock layer: _tools.json (the 81 verbatim schemas),
                                         <tool>.md for all 81 tools, _data/ for per-input answers
  evals/variants/<v>/mocks/robinhood/    per non-base variant, an overlay of the tools that differ from base
  evals/<case>/                          base-variant cases (prompt.md, graders/*.md)
  evals/variants/<v>/<case>/             cases that run against variant <v>
  evals/triggers/trig-<skill>-NN/        trigger cases from evalkit/triggers/<skill>.jsonl

Why variants are directories, not connector plugins: `claude plugin eval` layers mocks from the eval root
down to each case directory (a deeper mocks/<server>/<tool>.md replaces a shallower one), refuses a case
`plugins:` entry that lives inside the eval suite, and serves a mock directory that matches no declared
server as a standalone server. So the mock directory `robinhood` becomes the server `robinhood` in every
arm (tools `mcp__robinhood__<tool>`), and a case picks a variant by where it lives. See evalkit/README.md.

`--golden` runs the skill scripts on inputs built from the fixture and writes evalkit/golden/demo.json,
the numbers the README quotes (tools/check_readme.py compares them).

Stdlib only; Python 3.9+. No network access; `--golden` runs local Python scripts only.
"""

