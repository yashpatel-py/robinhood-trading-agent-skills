def build_golden(allow_partial: bool) -> Tuple[Dict[str, Any], List[str]]:
    world = World("base", None)
    g = Golden(world)
    problems: List[str] = []
    items_out: Dict[str, Any] = {}
    complete = True
    for item in golden_items(g):
        script = find_script(item["script"])
        entry: Dict[str, Any] = {"script": None, "op": item["op"], "spec": item["spec"]}
        if script is None:
            complete = False
            entry.update({"status": "script_missing", "values": None, "matches_spec": None,
                          "input": item["inputs"][0]})
            problems.append("%s: %s.py not found in %s" % (item["id"], item["script"],
                                                            ", ".join(SCRIPT_CANDIDATES[item["script"]])))
            items_out[item["id"]] = entry
            continue
        entry["script"] = script.relative_to(REPO_ROOT).as_posix()
        output, used, errors = None, None, []
        for candidate in item["inputs"]:
            try:
                result = run_script(script, item["op"], candidate)
            except (GenError, subprocess.TimeoutExpired) as exc:
                errors.append(str(exc))
                continue
            if result.get("ok"):
                output, used = result, candidate
                break
            errors.append(compact(result.get("errors") or result)[:400])
        if output is None:
            complete = False
            entry.update({"status": "script_failed", "values": None, "matches_spec": None,
                          "input": item["inputs"][0], "errors": errors})
            problems.append("%s: %s failed: %s" % (item["id"], entry["script"], "; ".join(errors)[:600]))
            items_out[item["id"]] = entry
            continue
        values = item["extract"](output)
        mismatches = [k for k, v in item["spec"].items() if not _same(v, values.get(k))]
        entry.update({"status": "ok", "input": used, "values": values,
                      "matches_spec": not mismatches, "mismatched_fields": mismatches,
                      "status_line": output.get("status_line") or output.get("first_line")})
        if mismatches:
            complete = False
            problems.append("%s: script output differs from the build spec on %s (spec %s, script %s)" % (
                item["id"], ", ".join(mismatches), {k: item["spec"][k] for k in mismatches},
                {k: values.get(k) for k in mismatches}))
        items_out[item["id"]] = entry
    readme = {}
    for key, entry in items_out.items():
        for field, value in (entry.get("values") or {}).items():
            readme["%s.%s" % (key, field)] = value
    doc = {
        "$comment": ("Golden numbers for the README demo, computed by running the skill scripts on the fixture "
                     "household (synthetic data). Regenerate with: python3 evalkit/gen_evals.py --golden. "
                     "tools/check_readme.py compares README numbers with 'readme'."),
        "generated_by": "evalkit/gen_evals.py --golden",
        "fixture": "evalkit/fixtures/household.json",
        "anchor": render.iso_et(world.now_local),
        "complete": complete,
        "readme": readme,
        "items": items_out,
    }
    if not complete and not allow_partial:
        problems.insert(0, "golden numbers are incomplete (pass --allow-partial to write them anyway)")
    return doc, problems


# --------------------------------------------------------------------------- CLI

def parse_variants(text: str) -> List[str]:
    if text == "all":
        return list(VARIANTS)
    wanted = [v.strip() for v in text.split(",") if v.strip()]
    bad = [v for v in wanted if v not in VARIANTS]
    if bad:
        raise GenError("unknown variant(s): %s (known: %s)" % (", ".join(bad), ", ".join(VARIANTS)))
    return wanted


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the Preflight eval suite from the fixture household.")
    parser.add_argument("--anchor", default=None,
                        help="ISO 8601 anchor time (default: the fixture's 2026-11-16T20:05:00-05:00) or 'today'")
    parser.add_argument("--variant", default="all", help="all, or a comma list of: %s" % ", ".join(VARIANTS))
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="output directory (default: <repo>/evals)")
    parser.add_argument("--check", action="store_true", help="compare with the tree on disk; write nothing")
    parser.add_argument("--golden", action="store_true", help="compute evalkit/golden/demo.json instead")
    parser.add_argument("--allow-partial", action="store_true",
                        help="--golden: write the file even when a script is missing or disagrees with the spec")
    parser.add_argument("--quiet", action="store_true")
    ns = parser.parse_args(argv)
    try:
        if ns.golden:
            doc, problems = build_golden(ns.allow_partial)
            text = pretty(doc)
            if ns.check:
                current = GOLDEN_PATH.read_text(encoding="utf-8") if GOLDEN_PATH.is_file() else ""
                if current != text:
                    problems.append("evalkit/golden/demo.json is out of date; run gen_evals.py --golden")
                for p in problems:
                    print("gen_evals: %s" % p, file=sys.stderr)
                return 1 if problems else 0
            for p in problems:
                print("gen_evals: %s" % p, file=sys.stderr)
            if problems and not ns.allow_partial:
                return 1
            GOLDEN_PATH.parent.mkdir(parents=True, exist_ok=True)
            GOLDEN_PATH.write_text(text, encoding="utf-8")
            if not ns.quiet:
                print("gen_evals: wrote %s (complete=%s)" % (GOLDEN_PATH.relative_to(REPO_ROOT), doc["complete"]))
            return 0
        variants = parse_variants(ns.variant)
        warnings: List[str] = []
        files = build_tree(ns.anchor, variants, warnings)
        out = Path(ns.out)
        for w in warnings:
            print("gen_evals: warning: %s" % w, file=sys.stderr)
        if ns.check:
            problems = check_tree(out, files, variants)
            for p in problems:
                print("gen_evals: %s" % p, file=sys.stderr)
            if problems:
                print("gen_evals: %d problem(s); run python3 evalkit/gen_evals.py to regenerate" % len(problems),
                      file=sys.stderr)
                return 1
            if not ns.quiet:
                print("gen_evals: %s is up to date (%d files)" % (out, len(files)))
            return 0
        written, removed = write_tree(out, files, variants)
        if not ns.quiet:
            cases = len({k.rsplit("/prompt.md", 1)[0] for k in files if k.endswith("/prompt.md")})
            print("gen_evals: %d files (%d written, %d removed), %d cases, variants: %s" % (
                len(files), written, removed, cases, ", ".join(variants)))
        return 0
    except (GenError, FixtureError, TemplateError) as exc:
        print("gen_evals: error: %s" % exc, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
